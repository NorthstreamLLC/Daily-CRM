/**
 * ICONS.
 *
 * One family throughout the app: Lucide (ISC licensed), inlined rather than
 * installed. Two reasons - no npm dependency to break, and nothing ships to the
 * browser except the handful of glyphs actually used.
 *
 * Every icon is 24x24 on a 2px round stroke, so they sit together correctly at
 * any size. Icons are decorative by default; anything carrying meaning on its
 * own needs an accessible label from the caller.
 */
import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement> & {
  /** Pixel size for both width and height. Defaults to 16. */
  size?: number;
  /** Supply when the icon is the only thing conveying meaning. */
  label?: string;
};

function Svg({ size = 16, label, children, ...rest }: IconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
      {...rest}
    >
      {children}
    </svg>
  );
}

